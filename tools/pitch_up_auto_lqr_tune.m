%% pitch_up_auto_lqr_tune.m
% Print-only tuner for the pitch-up AUTO-AIM LQR gains.
%
% Firmware edit target:
%   application/gimbal/gimbal.c
%   PITCH_UP_AUTO_LQR_K_THETA / PITCH_UP_AUTO_LQR_K_OMEGA
%
% Runtime hot-tune target:
%   pitch_up_auto_lqr_k_theta / pitch_up_auto_lqr_k_omega
%
% This script intentionally does not generate PITCH_UP_LQR_K_*.
% Normal, non-auto pitch-up has its own script:
%   tools/pitch_up_lqr_tune.m
%
% Firmware control law:
%   e_theta = measure - ref
%   e_omega = speed - ref_vel
%   tau_lqr = -k_theta * e_theta - k_omega * e_omega
%
% Auto-aim branch in firmware:
%   if pitch_up_auto_ref_active != 0:
%       k = [pitch_up_auto_lqr_k_theta, pitch_up_auto_lqr_k_omega]
%   else:
%       k = [PITCH_UP_LQR_K_THETA, PITCH_UP_LQR_K_OMEGA]

clear; clc;

control_mode = "auto";

torque_limit_nm = 7.00;          % PITCH_UP_TORQUE_LIMIT_NM
auto_torque_slew_nm_s = 1000.0;  % PITCH_UP_AUTO_TORQUE_SLEW_RATE_NM_S

%% Auto-aim design plant
% Shared pitch-up model identified from the 5-stage pitch-up dataset.
% This script computes and prints only the auto K generated by the current
% Q/R weights below.
J = 0.011526;        % kg*m^2, PITCH_UP_MODEL_J_KG_M2
Bv_design = 0.063380; % N*m*s/rad, PITCH_UP_MODEL_B_NMS_RAD
gravity_sin_nm = 0.373492;  % PITCH_UP_MODEL_GS_Q_NM
gravity_cos_nm = -0.929636; % PITCH_UP_MODEL_GC_Q_NM
coulomb_nm = 0.333765;      % PITCH_UP_MODEL_TAU_C_NM
omega_eps_rad_s = 0.0500;   % PITCH_UP_MODEL_OMEGA_EPS_RAD_S
motorSign = 1;      % +1: positive motor torque increases IMU pitch angle

%% Auto-aim LQR weights
q_theta = 100.0;  % angle error weight; larger is more aggressive
q_omega = 0.4;      % angular velocity weight; larger adds damping
r_tau   = 1.0;      % torque cost; larger is more conservative

Q = diag([q_theta, q_omega]);
R = r_tau;

%% Continuous plant
A = [0, 1;
     0, -Bv_design / J];
B = [0;
     motorSign / J];

if rank(ctrb(A, B)) < size(A, 1)
    error('Pitch-up auto-aim plant is not controllable. Check J, Bv_design, and motorSign.');
end

K_auto = lqr(A, B, Q, R);
Acl = A - B * K_auto;
closed_loop_poles = eig(Acl);

if any(K_auto <= 0)
    warning('Computed K has non-positive entries. Check motorSign and the firmware torque sign.');
end

%% Print copy blocks only
fprintf('Pitch-up LQR tune, control_mode = %s\n', char(control_mode));
fprintf('Plant: J = %.6f kg*m^2, Bv_design = %.6f N*m*s/rad, motorSign = %.0f\n', ...
        J, Bv_design, motorSign);
fprintf('Gravity/friction: GS = %.6f Nm, GC = %.6f Nm, FCS = %.6f Nm, omega_eps = %.4f rad/s\n', ...
        gravity_sin_nm, gravity_cos_nm, coulomb_nm, omega_eps_rad_s);
fprintf('Weights: q_theta = %.6g, q_omega = %.6g, r_tau = %.6g\n', ...
        q_theta, q_omega, r_tau);
fprintf('Torque limit = %.2f Nm, auto slew = %.2f Nm/s\n', ...
        torque_limit_nm, auto_torque_slew_nm_s);
fprintf('\n');

fprintf('K_auto from current Q/R = [%.6ff, %.6ff]\n', K_auto(1), K_auto(2));
fprintf('Closed-loop poles with current Q/R K = %.6f%+.6fi, %.6f%+.6fi\n', ...
        real(closed_loop_poles(1)), imag(closed_loop_poles(1)), ...
        real(closed_loop_poles(2)), imag(closed_loop_poles(2)));
fprintf('\n');

fprintf('--- paste auto-aim K macros into application/gimbal/gimbal.c ---\n');
fprintf('#define PITCH_UP_AUTO_LQR_K_THETA           %.6ff\n', K_auto(1));
fprintf('#define PITCH_UP_AUTO_LQR_K_OMEGA           %.6ff\n', K_auto(2));
fprintf('\n');

fprintf('--- Ozone live write, no rebuild ---\n');
fprintf('pitch_up_auto_lqr_k_theta = %.6ff;\n', K_auto(1));
fprintf('pitch_up_auto_lqr_k_omega = %.6ff;\n', K_auto(2));
fprintf('\n');

fprintf('Do not paste this result into PITCH_UP_LQR_K_THETA / PITCH_UP_LQR_K_OMEGA.\n');
